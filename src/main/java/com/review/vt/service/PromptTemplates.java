    /* ---------- 语音识别结果的术语纠正 ---------- */

    /**
     * 语音识别的中文没问题，但英文技术术语极易被认成同音词（equals → ecos）。
     * 这里只让模型纠正术语，**不要改写口述内容本身**。
     *
     * @param topic      练习主题（提供语境）
     * @param hotwords   当前题目的考察点，提示模型这些词大概率会出现
     * @param transcript 识别出来的原文
     */
    public static String polishTranscriptUser(String topic, List<String> hotwords, String transcript) {
        return """
            练习主题：%s
            本题考察点：%s

            语音识别对中文没问题，但把英文技术术语认成了同音词。请把它们改回正确的行业写法。
            可能的误识形态：拼写缺字、被音译成中文、大小写丢失、术语被拆成普通词。

            严格要求：
            - **不要改写、不要润色、不要补内容、不要删内容**，说话人的原意和语序都要原样保持。
            - 只改明显是术语误识的词；普通中文口语词、口头禅（"嗯""就是""那个"）一律保留。
            - 术语按行业通用写法：equals、hashCode、volatile、synchronized、HashMap、happens-before、CAS、AQS、ThreadLocal 等。
            - text 字段里**只能放纠正后的正文本身**，不要复述指令、不要解释、不要加引号。

            待纠正原文：
            %s

            只输出一个合法 JSON 对象，不要输出 JSON 之外的任何文字、不要 markdown：
            {"text":"纠正后的正文"}
            """.formatted(topic,
                    hotwords == null || hotwords.isEmpty() ? "（未提供）" : String.join("、", hotwords),
                    transcript);
    }

    /* ---------- 知识点清单：拆范围 / 从作答发散 ---------- */

    /**
     * 把练习范围拆成知识点清单。**宁精勿滥**——只收面试真会问的点，
     * 每个点自带三档内容规格（考到哪为止）。重要度不在这里定，后续联网取证分级。
     */
    public static String scaffoldUser(String scope, String level) {
        return """
            练习范围：%s
            岗位难度：%s

            请把这个范围拆成一份**精炼**的面试知识点清单——目标是「覆盖高频考点」，不是「穷尽一切细节」。JSON 格式：
            {"categories":[{"name":"大类名","points":[{"name":"知识点名","quick":"速通档考到哪","std":"标准档考到哪","deep":"深挖档考到哪"},...]}]}

            要求：
            - **宁精勿滥**：只收**面试真会问**的点。源码逐行、内部字段协作、算法结构细节
              （红黑树旋转、高低位拆分、空节点协助扩容这类）**一律不收**。
            - 粒度：一个点 = 一个能独立答 1-2 分钟的考点，命名「主题 · 子点」
              （例如「HashMap · put过程」「ArrayList · 扩容机制」）。
              同一主题的概念/原理/参数可以分 2-3 个点，但**不要拆到实现细节**。
            - 三档内容规格（一句话，说清「考到哪为止」）：
              · quick（速通）：是什么、怎么用、什么场景选
              · std（标准）：主干流程、关键参数与默认值、为什么这么设计
              · deep（深挖）：边界陷阱、与同类的取舍对比。**这是天花板，不要写「源码实现」**
            - **严格在范围内**：范围外的技术不要列进来。
            - 规模：4 到 8 个大类，每类 3 到 8 个点，**总数 30 到 50 个**。
              这是一轮复习能刷完的量——宁可少而准，不要多而杂。
            - 只输出 JSON，不要输出别的文字，不要 markdown 代码块。
            """.formatted(scope, level == null || level.isBlank() ? "中级" : level);
    }

    /**
     * 给候选点做**重要度分级**。证据是联网搜索结果（大多数人的面试经验），
     * 不是让模型凭空判断——这是「重要度真实性」的关键。
     */
    public static String priorityUser(String candidateNames, String evidence) {
        return """
            候选知识点清单：
            %s

            %s

            请对照上面的搜索线索（大多数人的面试经验），给每个知识点标**面试重要度**。JSON 格式：
            {"priorities":[{"name":"原样照抄知识点名","priority":"high|medium|low","evidence":"一句话理由","hits":["命中的线索标题，最多3条"]}]}

            分级标准（严格照此，不要自由发挥）：
            - **high**（高频必考）：≥2 条查询都出现，或八股/面经类结果里反复出现的问法
            - **medium**（常见加分）：出现过但不密集，或常见但非必问
            - **low**（少见偏门）：只在源码解析/算法题解里出现，或搜索里几乎看不到
              ——这类只有「深挖」强度才会考，默认不进题池

            注意：
            - name 必须**原样照抄**候选清单里的名字，顺序一致，不要改写、不要增删
            - 搜索线索是**证据不是题目**——按「这个点被问得多不多」分级，不是照抄线索里的问法
            - 没有任何线索命中的点，按面试常识归入 medium 或 low，evidence 写「搜索未直接命中」
            - 只输出 JSON，不要输出别的文字。
            """.formatted(candidateNames, evidence.isBlank()
                    ? "（联网搜索未取到线索，按面试常识分级，宁可保守）"
                    : "联网搜索所得的面试线索（用来判断「这个点被问得多不多」）：\n" + evidence);
    }

    /**
     * 从用户作答里发散新知识点。**只收范围内**——越界的宁可不要，
     * 否则用户「多说一句」反而招来答不出的难题，下次就不敢展开了。
     */
    public static String harvestUser(String scope, String answers, java.util.Collection<String> existing) {
        return """
            练习范围：%s
            已有知识点：%s

            用户在答题时的口述：
            %s

            请从用户的口述里找出**练习范围内、但清单里还没有**的新知识点。JSON 格式：
            {"newPoints":[{"name":"知识点名","category":"大类","inScope":true|false,"from":"来自用户哪句话"}]}

            要求：
            - **inScope 必须严格判断**：只有确实落在练习范围内的才写 true。范围外的一律 false（哪怕用户主动提到了）。
              宁可漏发散，也不能越界——越界会让用户觉得「多说多错」。
            - 只挑用户**真正展开讲过**的思路，不要因为他提了个名词就引申出一整片新领域。
            - 命名沿用「主题 · 子点」格式，每条不超过 30 字。
            - 最多 5 条，没有合适的就返回空数组。只输出 JSON。
            """.formatted(scope, existing.isEmpty() ? "（无）" : String.join("、"), answers);
    }

    /* ---------- 阶段总结（AI 反馈，全复习的依据） ---------- */

    /**
     * 阶段总结：把「做了哪些练习 / 记忆 / 平均分 / 每次考试的 AI 评价」按固定格式喂给 AI，
     * 让它给出反馈。这份反馈是后面「全复习」的唯一依据。
     *
     * @param dataText 固定格式的阶段数据（见 StageSummaryService#dataText）
     */
    public static String stageSummaryUser(String stageName, String dataText) {
        return """
            阶段名称：%s

            我在这个阶段做了下面这些练习（这是全部真实数据，包括每次考试你的评价，不要虚构）：
            %s

            请给我一份阶段总结，JSON 格式：
            {"overall":"总体评估","strengths":["已经掌握得比较好的方面"],"keyWeaknesses":["最需要补的短板"],"nextSteps":["下一步怎么练"],"reviewScope":"为全复习框定的范围描述"}

            要求：
            - overall 说清三件事：这个阶段练了什么、整体掌握到什么程度、最突出的问题是什么。150 字以内。
            - strengths 与 keyWeaknesses 各 2 到 5 条，每条具体到知识点或能力项（例如"能说清线程池参数与拒绝策略的搭配"），
              禁止"表现良好""有待提高"这类空话。
            - nextSteps 2 到 4 条，可执行（例如"重点复习 JMM 与 happens-before，先做 5 道基础辨析再上场景题"）。
            - reviewScope 是给「全复习」出题用的**范围描述，一长串连贯的文字，不是清单**，
              **严格控制在 300 字以内**，必须包含：
              ① 这个阶段覆盖了哪些知识大块；
              ② 哪些知识点已经练过（全复习要覆盖到，但不要出成原题复现）；
              ③ 哪些是薄弱点、要优先考；
              ④ 深度要求（先基础辨析后场景大题，要能上手讲出来）。
            - 全文（含所有字段）不超过 1200 字，宁可精炼也不要写长。
            """.formatted(stageName, dataText);
    }
